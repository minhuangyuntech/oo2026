export function eventText(event: GameEvent, lang: Language) {
  const key = event.kind === "hit" && event.hp === 0 ? "destroyed" : event.kind;
  return playText[lang].eventsText[key].replace(/\{(\w+)\}/g, (_, key: string) => String(event[key as keyof GameEvent] ?? ""));
}
